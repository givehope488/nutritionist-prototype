/** 按名称查食材营养，查不到返回 null */
export function foodOf(name) {
  if (FOOD[name]) return FOOD[name];
  const alias = FOOD_ALIAS[name];
  if (alias && FOOD[alias]) return FOOD[alias];
  return null;
}
